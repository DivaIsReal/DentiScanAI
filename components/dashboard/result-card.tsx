"use client";

import { motion } from "framer-motion";
import {
  Sparkles,
  AlertTriangle,
  CheckCircle2,
  Activity,
  TrendingUp,
} from "lucide-react";
import { Progress } from "@/components/ui/progress";
import { Badge } from "@/components/ui/badge";
import type { ScanResult } from "@/types";
import { cn } from "@/lib/utils";

interface ResultCardProps {
  result: ScanResult;
}

export function ResultCard({ result }: ResultCardProps) {
  const urgencyMap = {
    low: {
      label: "Low Risk",
      variant: "success" as const,
      icon: CheckCircle2,
      ring: "from-emerald-500 to-teal-500",
    },
    medium: {
      label: "Medium Risk",
      variant: "warning" as const,
      icon: Activity,
      ring: "from-amber-500 to-orange-500",
    },
    high: {
      label: "High Risk",
      variant: "destructive" as const,
      icon: AlertTriangle,
      ring: "from-rose-500 to-red-500",
    },
  };
  const u = urgencyMap[result.urgency];
  const UrgencyIcon = u.icon;

  return (
    <motion.div
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      className="glass rounded-2xl p-6 space-y-5"
    >
      <div className="flex items-start justify-between">
        <div>
          <h3 className="font-semibold flex items-center gap-2">
            <Sparkles className="w-4 h-4 text-cyan-500" />
            AI Analysis Result
          </h3>
          <p className="text-xs text-muted-foreground mt-0.5">
            Generated by DentiScan AI · Confidence {result.confidenceScore}%
          </p>
        </div>
        <Badge variant={u.variant}>
          <UrgencyIcon className="w-3 h-3 mr-1" />
          {u.label}
        </Badge>
      </div>

      {/* Score ring */}
      <div className="flex items-center gap-6">
        <div className="relative w-28 h-28 flex-shrink-0">
          <svg className="absolute inset-0 -rotate-90" viewBox="0 0 100 100">
            <circle
              cx="50"
              cy="50"
              r="42"
              fill="none"
              stroke="currentColor"
              strokeWidth="8"
              className="text-muted/30"
            />
            <motion.circle
              cx="50"
              cy="50"
              r="42"
              fill="none"
              stroke="url(#scoreGradient)"
              strokeWidth="8"
              strokeLinecap="round"
              strokeDasharray={`${(result.overallScore / 100) * 264} 264`}
              initial={{ strokeDasharray: "0 264" }}
              animate={{ strokeDasharray: `${(result.overallScore / 100) * 264} 264` }}
              transition={{ duration: 1, ease: "easeOut" }}
            />
            <defs>
              <linearGradient id="scoreGradient" x1="0" y1="0" x2="1" y2="1">
                <stop offset="0%" stopColor="#22d3ee" />
                <stop offset="100%" stopColor="#0284c7" />
              </linearGradient>
            </defs>
          </svg>
          <div className="absolute inset-0 flex flex-col items-center justify-center">
            <div className="text-2xl font-bold gradient-text font-display">
              {result.overallScore}%
            </div>
            <div className="text-[10px] text-muted-foreground uppercase tracking-wider">
              Healthy
            </div>
          </div>
        </div>

        <div className="flex-1 space-y-3">
          {result.conditions
            .filter((c) => c.name !== "Gusi Sehat")
            .map((cond, i) => (
              <motion.div
                key={cond.name}
                initial={{ opacity: 0, x: 20 }}
                animate={{ opacity: 1, x: 0 }}
                transition={{ delay: i * 0.1 }}
              >
                <div className="flex items-center justify-between mb-1">
                  <span className="text-sm font-medium flex items-center gap-2">
                    <span
                      className={cn(
                        "w-1.5 h-1.5 rounded-full",
                        cond.detected ? "bg-red-500" : "bg-emerald-500"
                      )}
                    />
                    {cond.name}
                  </span>
                  <span className="text-xs font-semibold tabular-nums">
                    {cond.confidence}%
                  </span>
                </div>
                <Progress
                  value={cond.confidence}
                  indicatorClassName={cn(
                    cond.detected
                      ? cond.confidence >= 80
                        ? "from-red-500 to-rose-500 bg-gradient-to-r"
                        : "from-amber-500 to-orange-500 bg-gradient-to-r"
                      : "from-emerald-500 to-teal-500 bg-gradient-to-r"
                  )}
                />
              </motion.div>
            ))}
        </div>
      </div>

      {/* AI summary */}
      <div className="rounded-xl bg-cyan-500/5 border border-cyan-500/15 p-4">
        <div className="flex items-start gap-3">
          <div className="w-8 h-8 rounded-lg bg-gradient-to-br from-cyan-500 to-sky-600 flex items-center justify-center flex-shrink-0">
            <Sparkles className="w-4 h-4 text-white" />
          </div>
          <div className="space-y-2 text-sm">
            <div>
              <div className="font-semibold text-cyan-700 dark:text-cyan-300 mb-0.5">
                Summary
              </div>
              <p className="text-foreground/90">{result.summary}</p>
            </div>
            <div>
              <div className="font-semibold text-cyan-700 dark:text-cyan-300 mb-0.5">
                Recommendation
              </div>
              <p className="text-foreground/90">{result.recommendation}</p>
            </div>
          </div>
        </div>
      </div>
    </motion.div>
  );
}
